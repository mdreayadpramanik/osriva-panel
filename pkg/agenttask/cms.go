// CMS adapters (docs/adr/0009-cms-wordpress.md). WordPress runs as two
// containers from the official images (WordPress + MariaDB) on a private
// network; it is managed with WP-CLI in short-lived containers.

const (
	CMSWPInstall = "cms.wp.install"
	CMSWPInfo    = "cms.wp.info"
	CMSWPVerify  = "cms.wp.verify"
	CMSWPUpdate  = "cms.wp.update"
	CMSRemove    = "cms.remove"

	CMSLabel = "dev.osriva.cms"

	WordPressImage = "wordpress:6.6-php8.3-apache"
	MariaDBImage   = "mariadb:11.4"
	WPCLIImage     = "wordpress:cli-2.11-php8.3"
)

func cmsTask(typ string) bool { return strings.HasPrefix(typ, "cms.") }

func cmsReadOnly(typ string) bool { return typ == CMSWPInfo || typ == CMSWPVerify }

// Docker object names of a WordPress instance.
func WPContainer(name string) string   { return "osriva-wp-" + name }
func WPDBContainer(name string) string { return "osriva-wp-" + name + "-db" }
func WPNetwork(name string) string     { return "osriva-wp-" + name }
func WPFilesVolume(name string) string { return "osriva-wp-" + name + "-files" }
func WPDBVolume(name string) string    { return "osriva-wp-" + name + "-db" }

var wpUser = regexp.MustCompile(`^[a-zA-Z0-9_.@-]{1,60}$`)

type WPInstallParams struct {
	Name          string `json:"name"`
	HostPort      int    `json:"host_port"`
	URL           string `json:"url"`
	Title         string `json:"title"`
	AdminUser     string `json:"admin_user"`
	AdminEmail    string `json:"admin_email"`
	AdminPassword string `json:"admin_password"` // generated by the panel, shown to the user once
}

type CMSNameParams struct {
	Name string `json:"name"`
}

type WPUpdateParams struct {
	Name   string `json:"name"`
	Target string `json:"target"` // core | plugins | themes
}

type CMSRemoveParams struct {
	Name       string `json:"name"`
	DeleteData bool   `json:"delete_data,omitempty"` // also delete the database and files volumes
}

// ValidSiteURL accepts an http(s) URL without credentials, query or fragment.
func ValidSiteURL(s string) bool {
	u, err := url.Parse(s)
	return err == nil && len(s) <= 300 && (u.Scheme == "http" || u.Scheme == "https") && u.Host != "" && u.User == nil &&
		u.RawQuery == "" && u.Fragment == "" && !strings.ContainsAny(s, " \t\r\n\"'`$\\")
}

func validateWPInstall(p WPInstallParams) error {
	if !AppName.MatchString(p.Name) {
		return fmt.Errorf("%w: name must be lower-case letters, digits and dashes (at most 40)", ErrInvalid)
	}
	if p.HostPort < 1 || p.HostPort > 65535 {
		return fmt.Errorf("%w: invalid host port", ErrInvalid)
	}
	if !ValidSiteURL(p.URL) {
		return fmt.Errorf("%w: site URL must be an http(s) URL", ErrInvalid)
	}
	if p.Title == "" || utf8.RuneCountInString(p.Title) > 100 || strings.ContainsAny(p.Title, "\x00\r\n") {
		return fmt.Errorf("%w: title must be 1-100 characters on one line", ErrInvalid)
	}
	if !wpUser.MatchString(p.AdminUser) {
		return fmt.Errorf("%w: admin user name may contain letters, digits and _ . @ -", ErrInvalid)
	}
	if a, err := mail.ParseAddress(p.AdminEmail); err != nil || a.Address != p.AdminEmail {
		return fmt.Errorf("%w: invalid admin e-mail", ErrInvalid)
	}
	if len(p.AdminPassword) < 16 || len(p.AdminPassword) > 128 || strings.ContainsAny(p.AdminPassword, "\x00\r\n") {
		return fmt.Errorf("%w: admin password must be 16-128 characters", ErrInvalid)
	}
	return nil
}

func validateCMS(typ string, raw json.RawMessage) error {
	switch typ {
	case CMSWPInstall:
		var p WPInstallParams
		if err := decodeStrict(raw, &p); err != nil {
			return err
		}
		return validateWPInstall(p)
	case CMSWPUpdate:
		var p WPUpdateParams
		if err := decodeStrict(raw, &p); err != nil {
			return err
		}
		if p.Target != "core" && p.Target != "plugins" && p.Target != "themes" {
			return fmt.Errorf("%w: target must be core, plugins or themes", ErrInvalid)
		}
		if !AppName.MatchString(p.Name) {
			return fmt.Errorf("%w: invalid name", ErrInvalid)
		}
	case CMSRemove:
		var p CMSRemoveParams
		if err := decodeStrict(raw, &p); err != nil {
			return err
		}
		if !AppName.MatchString(p.Name) {
			return fmt.Errorf("%w: invalid name", ErrInvalid)
		}
	case CMSWPInfo, CMSWPVerify:
		var p CMSNameParams
		if err := decodeStrict(raw, &p); err != nil {
			return err
		}
		if !AppName.MatchString(p.Name) {
			return fmt.Errorf("%w: invalid name", ErrInvalid)
		}
	default:
		return fmt.Errorf("%w: unknown task type %q", ErrInvalid, typ)
	}
	return nil
}

